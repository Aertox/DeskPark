const byId = new Map(CHARACTERS.map((c) => [c.id, c]));

export function getCharacter(id: string | undefined | null): PixelCharacter | undefined {
  return id ? byId.get(id as AvatarId) : undefined;
}

/** 没有指定形象时，按名字稳定地挑一个 */
export function characterForName(name: string): PixelCharacter {
  let h = 0;
  for (const ch of name) h = (h * 131 + ch.codePointAt(0)!) >>> 0;
  return CHARACTERS[h % CHARACTERS.length];
}

/** 展开为 16×16 的颜色网格（null 为透明） */
export function expandRows(c: PixelCharacter): (string | null)[][] {
  return c.rows.map((row) => {
    const full =
      row.length === 16
        ? row
        : row +
          [...row]
            .reverse()
            .map((ch) => c.swap?.[ch] ?? ch)
            .join('');
    return [...full].map((ch) => (ch === '.' ? null : (c.palette[ch] ?? null)));
  });
}
